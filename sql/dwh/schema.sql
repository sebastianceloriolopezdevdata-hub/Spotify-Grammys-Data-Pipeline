-- Star schema for the curated Grammy-to-Spotify linkage output.
-- The fact table grain is one accepted Grammy award / Spotify track pair.

CREATE TABLE IF NOT EXISTS dim_grammy_award (
    award_key CHAR(64) PRIMARY KEY,
    year SMALLINT NOT NULL CHECK (year BETWEEN 1958 AND 2019),
    title TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL,
    nominee TEXT NOT NULL,
    artist TEXT NOT NULL DEFAULT '',
    workers TEXT NOT NULL DEFAULT '',
    winner BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dim_spotify_track (
    track_id VARCHAR(64) PRIMARY KEY,
    artists TEXT NOT NULL DEFAULT '',
    album_name TEXT NOT NULL DEFAULT '',
    track_name TEXT NOT NULL,
    track_genre TEXT NOT NULL DEFAULT '',
    popularity SMALLINT CHECK (popularity BETWEEN 0 AND 100),
    duration_ms INTEGER CHECK (duration_ms > 0),
    explicit BOOLEAN,
    danceability DOUBLE PRECISION CHECK (danceability BETWEEN 0 AND 1),
    energy DOUBLE PRECISION CHECK (energy BETWEEN 0 AND 1),
    key SMALLINT CHECK (key BETWEEN -1 AND 11),
    loudness DOUBLE PRECISION,
    mode SMALLINT CHECK (mode IN (0, 1)),
    speechiness DOUBLE PRECISION CHECK (speechiness BETWEEN 0 AND 1),
    acousticness DOUBLE PRECISION CHECK (acousticness BETWEEN 0 AND 1),
    instrumentalness DOUBLE PRECISION CHECK (instrumentalness BETWEEN 0 AND 1),
    liveness DOUBLE PRECISION CHECK (liveness BETWEEN 0 AND 1),
    valence DOUBLE PRECISION CHECK (valence BETWEEN 0 AND 1),
    tempo DOUBLE PRECISION CHECK (tempo >= 0),
    time_signature SMALLINT CHECK (time_signature BETWEEN 0 AND 7)
);

CREATE TABLE IF NOT EXISTS fact_grammy_spotify_match (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    award_key CHAR(64) NOT NULL REFERENCES dim_grammy_award (award_key),
    track_id VARCHAR(64) NOT NULL REFERENCES dim_spotify_track (track_id),
    match_method TEXT NOT NULL,
    match_score DOUBLE PRECISION CHECK (match_score BETWEEN 0 AND 100),
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_grammy_spotify_pair UNIQUE (award_key, track_id)
);

CREATE INDEX IF NOT EXISTS idx_dim_grammy_award_year_category
    ON dim_grammy_award (year, category);
CREATE INDEX IF NOT EXISTS idx_fact_grammy_spotify_track
    ON fact_grammy_spotify_match (track_id);